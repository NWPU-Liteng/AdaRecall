#!/usr/bin/env bash
set -u
mkdir -p logs results data
LOG="logs/preflight.log"
: > "$LOG"

say() { echo "[$(date '+%F %T')] $*" | tee -a "$LOG"; }

say "== Basic command checks =="
for cmd in python3 pip curl docker ollama; do
  if command -v "$cmd" >/dev/null 2>&1; then
    say "FOUND $cmd: $(command -v "$cmd")"
  else
    say "MISSING $cmd"
  fi
done

say "== Python version =="
python3 --version 2>&1 | tee -a "$LOG" || true

DIRECT_OK=0
PROXY_OK=0
SELECTED_PROXY=""

say "== Direct network test =="
if timeout 8s curl -fsS --max-time 6 https://pypi.org/simple/ >/dev/null 2>&1; then
  DIRECT_OK=1
  say "Direct network OK"
else
  say "Direct network FAILED"
fi

say "== Proxy candidates test =="
PROXIES=(
  "http://127.0.0.1:21500"
  "http://127.0.0.1:7890"
  "http://127.0.0.1:7892"
  "http://localhost:21500"
  "http://localhost:7890"
  "http://localhost:7892"
)

for p in "${PROXIES[@]}"; do
  say "Testing proxy $p"
  if timeout 8s curl -fsS --max-time 6 --proxy "$p" https://pypi.org/simple/ >/dev/null 2>&1; then
    PROXY_OK=1
    SELECTED_PROXY="$p"
    say "Proxy OK: $p"
    break
  else
    say "Proxy failed: $p"
  fi
done

cat > .env.runtime <<EOF_ENV
# Generated by scripts/preflight.sh
DIRECT_OK=$DIRECT_OK
PROXY_OK=$PROXY_OK
SELECTED_PROXY=$SELECTED_PROXY
EXPERIMENT_OFFLINE_MODE=0
OLLAMA_BASE_URL=http://127.0.0.1:11434
OLLAMA_MODEL=qwen3:4b
OLLAMA_EMBED_MODEL=
EOF_ENV

if [ "$DIRECT_OK" -eq 0 ] && [ "$PROXY_OK" -eq 0 ]; then
  say "No usable external network detected. Offline-safe mode will be used."
  python3 - <<'PY'
from pathlib import Path
path = Path(".env.runtime")
text = path.read_text()
path.write_text(text.replace("EXPERIMENT_OFFLINE_MODE=0", "EXPERIMENT_OFFLINE_MODE=1"))
PY
fi

if [ "$PROXY_OK" -eq 1 ]; then
  cat >> .env.runtime <<EOF_ENV
http_proxy=$SELECTED_PROXY
https_proxy=$SELECTED_PROXY
HTTP_PROXY=$SELECTED_PROXY
HTTPS_PROXY=$SELECTED_PROXY
PIP_DEFAULT_TIMEOUT=20
PIP_RETRIES=2
EOF_ENV
fi

say "== Docker check =="
if command -v docker >/dev/null 2>&1; then
  timeout 8s docker info >/dev/null 2>&1 && say "Docker usable" || say "Docker exists but not usable without permission or daemon not running"
fi

say "== Ollama check =="
if command -v ollama >/dev/null 2>&1; then
  timeout 8s ollama list 2>&1 | tee -a "$LOG" || say "Ollama exists but service/model list unavailable"
fi

say "Preflight finished. Runtime env written to .env.runtime"
exit 0
